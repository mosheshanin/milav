/** Объект урока темы-бинъяна в порядке полей, как в остальных файлах. */
export function buildVerbLesson(binyan: Binyan, number: number): Record<string, unknown> {
  const topic = VERB_TOPICS[binyan];
  if (!topic) throw new Error(`для бинъяна ${binyan} генератора уроков нет`);
  const spec = topic.lessons[number - 1];
  const id = `${binyan}-${number}`;
  if (!spec) throw new Error(`урока ${id} нет в списке`);
  return {
    $schema: "../schema.json",
    id,
    topicId: binyan,
    section: "verbs",
    topic: topic.topic,
    number,
    free: number <= FREE_LESSONS_PER_TOPIC,
    title: spec.title,
    words: spec.verbs.map((v) => {
      const { infinitive, verb } = topic.conjugate(v.root);
      // У страдательных глаголов повелительного нет: блок убираем целиком (неполный блок схема не пропускает).
      if (v.noImperative) delete verb.imperative;
      const fill = (text: string, field: "he" | "translit") =>
        text.replace(/\{(ms|fs)\}/g, (_, key: "ms" | "fs") => (field === "he" ? verb.present[key].he : stripStress(verb.present[key].translit)));
      return {
        id: `${id}-${v.key}`,
        he: infinitive.he,
        niqqud: infinitive.niqqud,
        translit: infinitive.translit,
        ru: v.ru,
        // Фраза «אני {ms} …» получает пометку speaker и женский вариант с {fs} (docs/CONTENT.md, «Фразы от первого лица»).
        example: withFemaleVariant({ he: fill(v.phrase.he, "he"), translit: fill(v.phrase.translit, "translit"), ru: v.phrase.ru }, verb.present.ms, verb.present.fs, v.phrase.ruFemale),
        verb,
        reviewed: false,
      };
    }),
  };
}

