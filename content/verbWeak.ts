/**
 * Уроки «Слабые корни» (тема `weak`, раздел «Глаголы», задача 9, часть «Слабые корни, часть 1», 18.10): 30 самых частых
 * глаголов пааль со слабыми корнями (гзарами), по 10 в уроке. Решения владельца: формы набираются вручную по учебной таблице,
 * без генератора под каждую гзару (вопрос 54), все формы целиком (вопрос 65, и), код в чат не выводится.
 *
 * Как записано. Форма это пара `[огласованное написание, транскрипция]`. Иврит без огласовок (`he`) получается из огласованного
 * автоматически (`hebrewOf`), поэтому одна и та же буква не набирается дважды. В транскрипции ударение набрано апострофом
 * после гласной (`холе'х`) и превращается в знак ударения U+0301 при сборке урока. Односложные формы без ударения.
 * Ударение и транскрипция по стандарту `docs/CONTENT.md`; ь вместо ъ после согласной перед ע и א (йодьи'м), удвоение не пишется.
 *
 * Проверяет носитель: все формы `reviewed: false` (вопрос 65). Исправления вносят прямо в JSON урока, этот файл после
 * создания файлов уроков больше не запускают (`npm run content:verbs -- --topic weak`, существующие файлы не трогаются).
 */
type F = readonly [niqqud: string, translit: string];

export interface WeakVerbSpec {
  /** Латинский ключ слова: id будет `weak-<урок>-<ключ>`. */
  key: string;
  /** Бинъян; если не указан, пааль (уроки 1–3). Уроки 4–6 (часть 2, 18.10): хифъиль, пиэль, нифъаль, в каждом уроке один. */
  binyan?: Binyan;
  root: string;
  gizra: Gizra[];
  /** Перевод инфинитива. */
  ru: string;
  inf: F;
  /**
   * Фраза-пример с глаголом в настоящем времени: иврит, транскрипция без ударения, перевод. Фраза «אני <ms> …» сама получает
   * женский вариант (docs/CONTENT.md, «Фразы от первого лица»); четвёртый элемент нужен, если женщина по-русски скажет иначе.
   */
  phrase: readonly [he: string, translit: string, ru: string, ruFemale?: string];
  present: readonly [F, F, F, F];
  past: readonly [F, F, F, F, F, F, F, F, F];
  future: readonly [F, F, F, F, F, F, F, F, F, F];
  /** Повелительного нет у глаголов, у которых оно не употребляется (לדעת, לרצות, לאהוב…): блок не создаётся. */
  imperative?: readonly [F, F, F, F];
}

export interface WeakLessonSpec {
  title: string;
  verbs: WeakVerbSpec[];
}

/** Иврит без огласовок: убираем знаки огласовок, дагеш, точки шин и син. */
export function hebrewOf(niqqud: string): string {
  return niqqud.replace(/[֑-ׇ]/g, "");
}

function toForm([niqqud, translit]: F): WordForm {
  return { he: hebrewOf(niqqud), niqqud, translit: translit.replaceAll("'", ACUTE) };
}

function formSet<K extends string>(keys: readonly K[], forms: readonly F[]): Record<K, WordForm> {
  if (forms.length !== keys.length) throw new Error(`ожидалось форм: ${keys.length}, набрано: ${forms.length}`);
  return Object.fromEntries(keys.map((k, i) => [k, toForm(forms[i]!)])) as Record<K, WordForm>;
}

