-- Род ученика для фраз-примеров (решение владельца 22.10, docs/SPEC.md «Род во фразах-примерах»).
--
-- Фразы от первого лица в уроках бывают мужские («אני הולך») и женские («אני הולכת»), озвучены голосом того же рода.
-- Ученик выбирает в «Настройках», от чьего лица их показывать: 'm' мужчины (по умолчанию, так написаны все основные
-- фразы) или 'f' женщины. Хранится на сервере, чтобы выбор был одинаковым на всех устройствах.
ALTER TABLE user_stats ADD COLUMN gender TEXT NOT NULL DEFAULT 'm' CHECK (gender IN ('m', 'f'));
