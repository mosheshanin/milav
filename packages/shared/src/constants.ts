/** Правила викторины. У обычных уроков и у алфавита они свои (решение владельца, 13.10). */
export interface QuizRules {
  /** Сколько вопросов задают. */
  size: number;
  /** Сколько вопросов каждого типа. */
  perType: number;
  /** Сколько правильных ответов нужно, чтобы урок считался сданным. */
  pass: number;
  /** Сколько ошибок допустимо; следующая ошибка прерывает викторину. */
  maxMistakes: number;
}

/** Викторина обычного урока: 25 вопросов, 5 типов по 5, сдан при 20, шестая ошибка прерывает. */
